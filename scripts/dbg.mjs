import playwright from 'playwright';
const { chromium } = playwright;
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 1280, height: 900 } });
p.on('pageerror', e => console.log('PAGEERROR', e.message));
await p.goto('http://127.0.0.1:4300/login', { waitUntil: 'networkidle' });
await p.getByRole('button', { name: 'Fill credentials' }).click();
await p.getByRole('button', { name: /^Log in/ }).click();
await p.waitForURL('http://127.0.0.1:4300/');
await p.goto('http://127.0.0.1:4300/assessment/pretest/easy', { waitUntil: 'networkidle' });
console.log('INTRO BUTTONS:', await p.locator('button').allTextContents());
await p.getByRole('button', { name: /Resume the test/ }).click();
await p.waitForSelector('.question-card');
console.log('CHOICES:', await p.locator('.choice').count());
await p.locator('.choice').nth(1).click();
console.log('FOOT BUTTONS:', await p.locator('.question-foot button').allTextContents());
console.log('DISABLED:', await p.locator('.question-foot button').evaluateAll(els => els.map(e => [e.textContent, e.disabled])));
await p.screenshot({ path: '/tmp/dbg.png', fullPage: true });
await b.close();
